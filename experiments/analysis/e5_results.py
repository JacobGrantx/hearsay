"""E5 (post-hoc follow-up, pre-registered in EXPERIMENTS.md, "E5: talk with something to carry").

Every number comes from the run directories alone: record.json, layout.json, events.jsonl and state.jsonl.gz.

    .venv/bin/python experiments/analysis/e5_results.py

Writes experiments/analysis/output/e5_results.md and .json.
"""
from __future__ import annotations

import json
import os

from measures import COORD
from runs import OUTPUT, RESULTS, SEASONS, Run, describe, fmt, paired

ARMS = ["e5_full", "e5_no_talk"]
STAMP = os.environ.get("DL_E5_STAMP", "20261106T112913Z")  # the E5 batch: one process per seed, tags s0 to s4
SEEDS = [0, 1, 2, 3, 4]
SECONDARY = ["spring_deliveries", "delivery_rate", "trips", "stings_per_trip", "bees_mean"]


def e5_runs(arm: str) -> dict[int, Run]:
    out = {}
    for d in sorted((RESULTS / arm).glob(f"{STAMP}_s*/seed-*")):
        if (d / "record.json").exists():
            r = Run(d)
            out[r.seed] = r
    return out


def near(x: int, y: int, cells, r: int) -> bool:
    return any(max(abs(x - cx), abs(y - cy)) <= r for cx, cy in cells)


def first_sightings(run: Run) -> dict[tuple[int, str, int], int]:
    """(bee, season, year) -> first tick its logged position was within bloom vision of that season's bloom."""
    bloom, bv, out = run.layout["bloom"], run.layout["bloom_vision"], {}
    for st in run.states:
        season = SEASONS[st["s"]]
        cells = bloom.get(season)
        if not cells:
            continue
        for b in st["b"]:
            key = (b[0], season, st["y"])
            if key not in out and near(b[1], b[2], cells, bv):
                out[key] = st["t"]
    return out


def colony_first_sighting(run: Run, seen: dict) -> dict[str, int]:
    """Ticks from each season's start to the first sighting by any bee, censored at the season length (year 1)."""
    L = run.layout["season_length"]
    return {s: min([t - i * L for (_, ss, y), t in seen.items() if ss == s and y == 0] + [L])
            for i, s in enumerate(SEASONS[:3])}


def talk_informed(run: Run, seen: dict) -> list[dict]:
    """Every delivery, classified by the pre-registered talk-informed and acted-on-talk rules."""
    L, bloom = run.layout["season_length"], run.layout["bloom"]
    pickups = run.of("bloom")
    heard: dict[int, list[dict]] = {}
    for e in run.of("say"):
        coords = [(int(x), int(y)) for x, y in COORD.findall(e["text"])]
        for b in e["heard_by"]:
            heard.setdefault(b, []).append(dict(t=e["t"], speaker=e["bee"], text=e["text"], coords=coords))
    decisions = [e for e in run.of("decision") if e.get("intent") == "go_to" and e.get("target")]
    out = []
    for d in run.of("delivery"):
        bee = d["bee"]
        pick = max((p for p in pickups if p["bee"] == bee and p["t"] <= d["t"]), key=lambda p: p["t"])
        season, year = SEASONS[(pick["t"] // L) % 4], pick["t"] // (4 * L)
        cells, first = bloom[season], seen[(bee, season, year)]
        hits = [h for h in heard.get(bee, []) if h["t"] < first and any(near(x, y, cells, 3) for x, y in h["coords"])]
        row = dict(seed=run.seed, bee=bee, delivery_t=d["t"], pickup_t=pick["t"], season=season,
                   first_sighting=first, talk_informed=bool(hits), acted=False, heard=[], first_go_to=None)
        if hits:
            go = [e for e in decisions if e["bee"] == bee and hits[0]["t"] <= e["t"] < first
                  and near(e["target"][0], e["target"][1], cells, 3)]
            row["acted"] = bool(go)
            row["first_go_to"] = dict(t=go[0]["t"], target=go[0]["target"]) if go else None
            for h in hits:
                s_first = seen.get((h["speaker"], season, year))
                row["heard"].append(dict(t=h["t"], speaker=h["speaker"], text=h["text"],
                                         speaker_had_seen=s_first is not None and s_first < h["t"]))
        out.append(row)
    return out


def bloom_talk(run: Run) -> dict:
    """Say events at home holding a coordinate within 3 cells of the current season's bloom, and their listeners."""
    L, bloom = run.layout["season_length"], run.layout["bloom"]
    says = [e for e in run.of("say") if near_any(e, bloom.get(SEASONS[(e["t"] // L) % 4]) or [])]
    return dict(says=len(run.of("say")), bloom_says=len(says), bloom_listeners=sum(len(e["heard_by"]) for e in says))


def near_any(e: dict, cells) -> bool:
    return any(near(int(x), int(y), cells, 3) for x, y in COORD.findall(e["text"]))


def main() -> None:
    res, md = {}, ["# E5 results (generated by experiments/analysis/e5_results.py; do not edit)", ""]
    data = {arm: e5_runs(arm) for arm in ARMS}
    seen = {arm: {s: first_sightings(r) for s, r in rs.items()} for arm, rs in data.items()}
    md += ["Run directories: " + ", ".join(f"{arm}/{STAMP}_s<n>/seed-<n> (seeds {sorted(data[arm])})" for arm in ARMS), ""]
    md += ["## Model health", "", "| arm | seed | decisions | mind_error | fallbacks | git_dirty | duration s |", "|---|---|---|---|---|---|---|"]
    for arm, rs in data.items():
        for s, r in rs.items():
            dec = r.of("decision")
            md.append(f"| {arm} | {s} | {len(dec)} | {len(r.of('mind_error'))} | {sum(1 for e in dec if e.get('fallback'))} "
                      f"| {r.record['provenance']['git_dirty']} | {r.record.get('seconds')} |")
    final = {arm: {s: r.final for s, r in rs.items()} for arm, rs in data.items()}
    md += ["", "## (a) Gathering", "", "| measure | e5_full | e5_no_talk |", "|---|---|---|"]
    res["a"] = {}
    for m in ["deliveries"] + SECONDARY:
        stats = {arm: describe({s: final[arm][s].get(m) for s in SEEDS if s in final[arm]}) for arm in ARMS}
        res["a"][m] = stats
        md.append(f"| {m} | {fmt(stats['e5_full'])} {list(stats['e5_full']['per_seed'].values())} "
                  f"| {fmt(stats['e5_no_talk'])} {list(stats['e5_no_talk']['per_seed'].values())} |")
    for arm in ARMS:
        cfs = {s: colony_first_sighting(data[arm][s], seen[arm][s]) for s in data[arm]}
        res["a"][f"first_sighting_{arm}"] = cfs
        md.append(f"| first bloom sighting, ticks into spring/summer/autumn ({arm}) | "
                  + "; ".join(f"s{s}: {list(v.values())}" for s, v in cfs.items()) + " | |")
    p = paired({s: final["e5_full"][s].get("deliveries") for s in final["e5_full"]},
               {s: final["e5_no_talk"][s].get("deliveries") for s in final["e5_no_talk"]}, seeds=SEEDS)
    res["a"]["paired_deliveries"] = p
    md += ["", f"Paired, e5_full minus e5_no_talk, deliveries, seeds {SEEDS}: differences {list(p['diffs'].values())}, "
               f"mean {p['mean']}, sd {p['sd']}, n {p['n']}: **{p['verdict']}**.", ""]
    md += ["## (b) Talk-informed deliveries", "", "| arm | seed | deliveries | talk-informed | acted on talk | say at home | say near current bloom | listeners of those |",
           "|---|---|---|---|---|---|---|---|"]
    res["b"], rows_all = {}, []
    for arm, rs in data.items():
        per = {}
        for s, r in rs.items():
            rows = talk_informed(r, seen[arm][s])
            bt = bloom_talk(r)
            ti, ac = sum(x["talk_informed"] for x in rows), sum(x["acted"] for x in rows)
            per[s] = dict(deliveries=len(rows), talk_informed=ti, acted=ac, **bt)
            md.append(f"| {arm} | {s} | {len(rows)} | {ti} | {ac} | {bt['says']} | {bt['bloom_says']} | {bt['bloom_listeners']} |")
            if arm == "e5_full":
                rows_all += rows
        res["b"][arm] = dict(per_seed=per, talk_informed=describe({s: v["talk_informed"] for s, v in per.items()}),
                             acted=describe({s: v["acted"] for s, v in per.items()}),
                             seeds_with_talk_informed=sum(1 for v in per.values() if v["talk_informed"]))
    b = res["b"]["e5_full"]
    md += ["", f"e5_full talk-informed deliveries per run: {fmt(b['talk_informed'])}; acted on talk: {fmt(b['acted'])}; "
               f"seeds with at least one: {b['seeds_with_talk_informed']} of {len(data['e5_full'])} "
               f"(supported if at least 2): **{'supported' if b['seeds_with_talk_informed'] >= 2 else 'not supported'}**.", ""]
    md += ["### Every talk-informed delivery in e5_full", ""]
    res["b"]["examples"] = [x for x in rows_all if x["talk_informed"]]
    for x in res["b"]["examples"]:
        h = x["heard"][0]
        md.append(f"- seed {x['seed']}, bee {x['bee']}, {x['season']}: heard at tick {h['t']} from bee {h['speaker']} "
                  f"(speaker had seen the bloom: {h['speaker_had_seen']}): \"{h['text']}\"; first sighting tick "
                  f"{x['first_sighting']}, picked up {x['pickup_t']}, delivered {x['delivery_t']}; acted on talk: {x['acted']}"
                  + (f" (go_to {x['first_go_to']['target']} at tick {x['first_go_to']['t']})" if x["first_go_to"] else "")
                  + f"; {len(x['heard'])} qualifying heard message(s) before the sighting.")
    if not res["b"]["examples"]:
        md.append("- none")
    res["b"]["all_full_deliveries"] = rows_all
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "e5_results.json").write_text(json.dumps(res, indent=1, default=str))
    (OUTPUT / "e5_results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
