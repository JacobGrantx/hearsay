"""Why trips failed in the main runs: a diagnosis that informs the E5 world, not a pre-registered result.

For every trip (a `trip` event) in the chosen arms: how it ended, how far it got, and how much life the bee
had when it turned back. Reads only the run directories.

    .venv/bin/python experiments/analysis/trip_diagnosis.py [arm ...]   # default: full no_talk rule_bees

Writes experiments/analysis/output/trip_diagnosis.md and .json.
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter, deque

from runs import OUTPUT, SEASONS, Run, runs

OUTCOMES = ["delivered", "died_stung", "died_no_sting", "back_stung", "back_no_sting"]


def path_distance(run: Run) -> dict[tuple[int, int], int]:
    """Shortest path in steps from home to every reachable open cell (4-neighbour, walls block)."""
    rows = run.layout["rows"]
    home = tuple(run.layout["home"])
    dist, queue = {home: 0}, deque([home])
    while queue:
        x, y = queue.popleft()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= ny < len(rows) and 0 <= nx < len(rows[0]) and rows[ny][nx] != "#" and (nx, ny) not in dist:
                dist[(nx, ny)] = dist[(x, y)] + 1
                queue.append((nx, ny))
    return dist


def outcome(trip: dict) -> str:
    if trip["delivered"]:
        return "delivered"
    stung = "stung" if trip["stings"] else "no_sting"
    return f"died_{stung}" if trip["outcome"] == "died" else f"back_{stung}"


def trips(run: Run) -> list[dict]:
    """One row per trip: season it started in, outcome, farthest path distance and the life left there."""
    dist, L = path_distance(run), run.layout["base_life"]
    season_len = run.layout["season_length"]
    states = run.states
    out = []
    for tr in run.of("trip"):
        start, end, bee = tr["start"], tr["t"], tr["bee"]
        season = SEASONS[(start // season_len) % 4]
        bloom_d = run.layout["bloom_distance"].get(season)
        far, life_at_far, life_start = -1, None, None
        for s in states[start:end + 1]:
            for b in s["b"]:
                if b[0] == bee:
                    d = dist.get((b[1], b[2]), 0)
                    if life_start is None:
                        life_start = b[3]
                    if d > far:
                        far, life_at_far = d, b[3]
        out.append(dict(seed=run.seed, bee=bee, start=start, end=end, season=season, outcome=outcome(tr),
                        reached_bloom=tr["reached_bloom"] is not None, far=far, bloom_d=bloom_d,
                        frac=(far / bloom_d) if bloom_d else None,
                        life_start=life_start / L if life_start is not None else None,
                        life_at_far=life_at_far / L if life_at_far is not None else None))
    return out


def med(xs: list) -> float | None:
    xs = [x for x in xs if x is not None]
    return round(statistics.median(xs), 3) if xs else None


def summarise(rows: list[dict]) -> dict:
    n = len(rows)
    c = Counter(r["outcome"] for r in rows)
    back = [r for r in rows if r["outcome"].startswith("back")]
    return dict(
        trips=n, **{k: c.get(k, 0) for k in OUTCOMES},
        reached_bloom=sum(r["reached_bloom"] for r in rows),
        got_within_bloom_d=sum(1 for r in rows if r["frac"] is not None and r["frac"] >= 1.0),
        median_frac=med([r["frac"] for r in rows]),
        median_life_start=med([r["life_start"] for r in rows]),
        median_life_at_turn_back=med([r["life_at_far"] for r in back]),
        median_frac_turned_back=med([r["frac"] for r in back]),
    )


def main(arms: list[str]) -> None:
    result, lines = {}, ["# Why trips failed (diagnosis for E5, generated by trip_diagnosis.py; do not edit)", "",
                         "Distances are path steps from home; `frac` is the farthest point of a trip divided by the "
                         "path distance to that season's bloom. Life is a share of base life L. A trip counts in the "
                         "season it started. `back` = came home without delivering.", ""]
    for arm in arms:
        rows = [r for run in runs(arm).values() for r in trips(run)]
        seeds = sorted({r["seed"] for r in rows})
        by_season = {s: summarise([r for r in rows if r["season"] == s]) for s in SEASONS}
        result[arm] = dict(seeds=seeds, all=summarise(rows), by_season=by_season)
        lines += [f"## {arm} (seeds {seeds})", "",
                  "| season | " + " | ".join(summarise([]).keys()) + " |",
                  "|---|" + "---|" * len(summarise([]))]
        for name, s in [("all", result[arm]["all"])] + list(by_season.items()):
            lines.append(f"| {name} | " + " | ".join(str(v) for v in s.values()) + " |")
        lines.append("")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "trip_diagnosis.json").write_text(json.dumps(result, indent=1))
    (OUTPUT / "trip_diagnosis.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1:] or ["full", "no_talk", "rule_bees"])
