"""Render the demo video from the run directories: make video [TITLE="..."] [REPO="..."].

Map segments are captured from bundled viewer pages by viewer/capture.py; captions are overlaid with
ffmpeg; cards and charts are drawn by cards.py and charts.py from experiments/analysis/output. All
segments are concatenated into demo/recordings/demo.mp4, SOURCES.md is written next to it from the
storyboard, and the stills go to demo/screenshots/. Scratch files live on /dev/shm and are deleted.
"""
import argparse
import re
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
import cards  # noqa: E402
import charts  # noqa: E402
from storyboard import E5, FPS, MAIN, SEGMENTS, step, total_seconds  # noqa: E402

PY = sys.executable
CAPTURE = REPO / "viewer" / "capture.py"
BUNDLE = REPO / "viewer" / "bundle.py"
STILLS = [  # (file, run, tick, bee, view)
    ("full_seed0_t34_bee5_first_sight.png", "MAIN", 34, 5, "8,5,42,29"),
    ("full_seed0_t184_bee1_warns.png", "MAIN", 184, 1, "0,13,30,35"),
    ("e5_full_seed0_t167_bee4_tells.png", "E5", 167.5, 4, "0,7,26,27"),
    ("e5_full_seed0_t355_bee1_old_place.png", "E5", 355, 1, None),
]


def default_title() -> str:
    h1 = next(line for line in (REPO / "README.md").read_text().splitlines() if line.startswith("# "))
    return re.sub(r"\s*\(working title\)\s*$", "", h1[2:].strip())


def default_repo() -> str:
    url = subprocess.run(["git", "-C", str(REPO), "remote", "get-url", "origin"], capture_output=True,
                         text=True).stdout.strip()
    url = re.sub(r"^[a-z]+://([^@/]*@)?", "", url)  # drop the scheme and any credentials
    return re.sub(r"\.git$", "", url)


def run(cmd: list) -> None:
    subprocess.run([str(c) for c in cmd], check=True)


def encode_args(crf: int, preset: str = "medium") -> list:
    return ["-c:v", "libx264", "-preset", preset, "-crf", str(crf), "-pix_fmt", "yuv420p", "-r", str(FPS)]


def map_segment(seg: dict, html: Path, work: Path) -> Path:
    raw, out = work / f"raw_{seg['id']}.mp4", work / f"seg_{seg['id']}.mp4"
    cmd = [PY, CAPTURE, html, raw, "--from", seg["t0"], "--to", seg["t1"], "--step", f"{step(seg):.6f}",
           "--fps", FPS]
    if seg.get("bee") is not None:
        cmd += ["--bee", seg["bee"]]
    if seg.get("view"):
        cmd += ["--view", seg["view"]]
    run(cmd)
    inputs, chain, last = ["-i", raw], [], "0:v"
    for i, (a, b, text) in enumerate(seg["captions"]):
        png = work / f"cap_{seg['id']}_{i}.png"
        cards.caption(text, png)
        inputs += ["-i", png]
        chain.append(f"[{last}][{i + 1}:v]overlay=0:0:enable='between(t,{a},{b})'[v{i}]")
        last = f"v{i}"
    run(["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", ";".join(chain), "-map", f"[{last}]",
         "-t", seg["seconds"], *encode_args(16), out])
    raw.unlink()
    return out


def card_segment(seg: dict, work: Path, title: str, repo: str) -> Path:
    png, out = work / f"card_{seg['id']}.png", work / f"seg_{seg['id']}.mp4"
    draw = {"title": lambda p: cards.title_card(title, p), "end": lambda p: cards.end_card(title, repo, p),
            "hypotheses": cards.hypotheses_card, "chart_e1": charts.chart_e1,
            "chart_caution": charts.chart_caution, "chart_e5": charts.chart_e5}[seg["card"]]
    draw(png)
    d = seg["seconds"]
    fade = f"fade=in:st=0:d=0.4,fade=out:st={d - 0.4}:d=0.4"
    run(["ffmpeg", "-y", "-loglevel", "error", "-loop", "1", "-framerate", FPS, "-i", png, "-t", d, "-vf", fade,
         *encode_args(16), out])
    return out


def write_sources(path: Path, title: str, repo: str, seconds: float) -> None:
    L = ["# Demo video: sources", "",
         "Generated by `demo/video/make_video.py` from `demo/video/storyboard.py` (do not edit by hand). "
         "Every map segment is a replay of the run directory named, rendered by `viewer/capture.py`. "
         "The moments were found by `experiments/analysis/find_moments.py` and every tick, life value and "
         "quote in a caption is copied from that run's `events.jsonl`.", "",
         f"Title: {title}. Repository shown: {repo}. Length: {seconds:g} s at {FPS} fps, 1280 x 720, no audio.", "",
         "| # | Segment | Seconds | Source | Ticks | Follows | Frame (cells) |", "|---|---|---|---|---|---|---|"]
    for i, s in enumerate(SEGMENTS, 1):
        if s["kind"] == "map":
            L.append(f"| {i} | {s['beat']} | {s['seconds']:g} | `{s['run']}` | {s['t0']} to {s['t1']} "
                     f"(step {step(s):.4f}) | {'bee ' + str(s['bee']) if s['bee'] is not None else 'colony'} | "
                     f"{s['view'] or 'whole map'} |")
        else:
            src = {"title": "README.md H1", "end": "card", "hypotheses": "main_results.json, e5_results.json",
                   "chart_e1": "main_results.json (E1)", "chart_caution": "main_results.json (naive avoidance, E4 listener)",
                   "chart_e5": "e5_results.json"}[s["card"]]
            L.append(f"| {i} | {s['card'].replace('_', ' ')} card | {s['seconds']:g} | {src} | | | |")
    L += ["", "## Captions", ""]
    for s in SEGMENTS:
        for a, b, text in s.get("captions", []):
            L.append(f"- `{s['id']}` {a:g} to {b:g} s: {text}")
    L += ["", "Chart numbers come from `experiments/analysis/output/` (written by `make analysis`). Re-render "
          "everything with `make video` (about 10 minutes; `TITLE=` and `REPO=` override the title and the "
          "repository line).", ""]
    path.write_text("\n".join(L))


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Render the demo video from the run directories.")
    ap.add_argument("--title", default=None, help="project name for the cards (default: README H1)")
    ap.add_argument("--repo", default=None, help="repository line on the end card (default: origin)")
    ap.add_argument("--out", type=Path, default=REPO / "demo" / "recordings" / "demo.mp4")
    ap.add_argument("--work", type=Path, default=Path("/dev/shm/dl-video-render"))
    ap.add_argument("--jobs", type=int, default=2, help="map segments captured at once (default 2)")
    ap.add_argument("--crf", type=int, default=24, help="x264 quality of the final file (default 24)")
    ap.add_argument("--no-stills", action="store_true", help="skip demo/screenshots/")
    args = ap.parse_args(argv)
    title, repo = args.title or default_title(), args.repo or default_repo()
    work = args.work
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    pages = {}
    for seg in SEGMENTS:
        if seg["kind"] == "map" and seg["run"] not in pages:
            pages[seg["run"]] = work / f"page_{len(pages)}.html"
            run([PY, BUNDLE, REPO / seg["run"], "-o", pages[seg["run"]], "--project", title])
    runs = {"MAIN": pages[MAIN], "E5": pages[E5]}
    with ThreadPoolExecutor(args.jobs) as pool:
        futs = {s["id"]: pool.submit(map_segment, s, pages[s["run"]], work) for s in SEGMENTS if s["kind"] == "map"}
        files = {s["id"]: card_segment(s, work, title, repo) for s in SEGMENTS if s["kind"] == "card"}
        files.update({k: f.result() for k, f in futs.items()})
    listing = work / "list.txt"
    listing.write_text("".join(f"file '{files[s['id']]}'\n" for s in SEGMENTS))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", listing,
         *encode_args(args.crf, "slow"), "-movflags", "+faststart", args.out])
    write_sources(args.out.parent / "SOURCES.md", title, repo, total_seconds())
    if not args.no_stills:
        for name, key, tick, bee, view in STILLS:
            cmd = [PY, CAPTURE, runs[key], REPO / "demo" / "screenshots" / name, "--from", tick, "--bee", bee]
            run(cmd + (["--view", view] if view else []))
    shutil.rmtree(work, ignore_errors=True)
    print(f"{args.out} ({args.out.stat().st_size / 1e6:.1f} MB, {total_seconds():g} s)")


if __name__ == "__main__":
    main()
